import { PULSE, ringPhase, ringOpacity, easeOut } from "../src/lib/rings/homePulse.js";
let f = 0; const ok = (c, m) => { console.log(`${c ? "PASS" : "FAIL"} ${m}`); if (!c) f++; };
const near = (a, b) => Math.abs(a - b) < 1e-9;
ok(PULSE.growMs === 3600 && PULSE.staggerMs === 1200 && PULSE.count * PULSE.staggerMs === PULSE.growMs, "3.6s growth, 1.2s apart, seamless");
ok(near(ringPhase(0, 0), 0) && near(ringPhase(1200, 1), 0) && near(ringPhase(2400, 2), 0), "rings start 1.2s apart");
ok(near(ringPhase(3600, 0), 0) && near(ringPhase(4800, 1), 0), "loops every 3.6s");
ok(near(ringPhase(0, 1), 2 / 3), "ring 2 mid-cycle at t=0 (no gap at start)");
ok(near(ringOpacity(0), 0) && near(ringOpacity(0.05), 0.3) && near(ringOpacity(0.1), 0.6), "opacity 0 to 60% over first 10%");
ok(near(ringOpacity(0.55), 0.3) && near(ringOpacity(1), 0), "linear fade to 0");
ok(near(easeOut(0), 0) && near(easeOut(1), 1) && easeOut(0.5) > 0.5, "size eases out");
console.log(f ? `${f} failed` : "all passed"); process.exit(f ? 1 : 0);
